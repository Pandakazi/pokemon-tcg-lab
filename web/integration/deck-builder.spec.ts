test('long names wrap in tray and gallery scroll returns after inspection',async({page,request})=>{
 const pool=await (await request.get('/api/v1/cards?category=Pokemon&q=Team+Rocket&page_size=50')).json()
 const card=pool.cards.sort((a:any,b:any)=>b.name.length-a.name.length)[0]
 expect(card.name.length).toBeGreaterThan(20)
 await page.goto('/deck-builder?category=Pokemon&q='+encodeURIComponent(card.name))
 const tile=page.locator(`[data-printing-id="${card.id}"]`)
 await expect(tile).toBeVisible()
 await tile.getByRole('button',{name:`Add ${card.name} to deck`,exact:true}).click()
 const tray=page.getByRole('complementary',{name:'Active deck'})
 const name=tray.getByRole('link',{name:card.name,exact:true})
 await expect(name).toBeVisible()
 expect(await name.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBeTruthy()
 await page.getByRole('button',{name:'Clear search'}).click()
 const gallery=page.getByRole('region',{name:'Card library results'})
 await expect(gallery).toHaveAttribute('aria-busy','false')
 await gallery.evaluate(el=>{el.scrollTop=500})
 await expect.poll(()=>gallery.evaluate(el=>el.scrollTop)).toBeGreaterThan(0)
 const candidate=page.locator('[data-printing-id]').nth(12)
 await candidate.scrollIntoViewIfNeeded()
 const position=await gallery.evaluate(el=>el.scrollTop)
 await candidate.getByRole('link').click()
 await expect(page.getByRole('heading',{name:'Card text',exact:true})).toBeVisible()
 await page.getByRole('link',{name:'← Back to Deck Builder'}).click()
 await expect(gallery).toHaveAttribute('aria-busy','false')
 await expect.poll(()=>gallery.evaluate(el=>el.scrollTop)).toBeCloseTo(position,0)
 await expect(tray.getByRole('link',{name:card.name,exact:true})).toBeVisible()
})
