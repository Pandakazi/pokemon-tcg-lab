test('save failure is surfaced and draft remains recoverable',async({page,request})=>{
 const card=(await (await request.get('/api/v1/cards?category=Pokemon&stages=Basic')).json()).cards[0]
 await command(request,{action:'quantity',printing_id:card.id,delta:1})
 await page.goto('/deck-builder');const tray=page.getByRole('complementary',{name:'Active deck'})
 await expect(tray).toContainText('IN PROGRESS')
 await page.route('**/api/v1/deck-workspace',async route=>{
  if(route.request().method()==='POST'&&route.request().postDataJSON().action==='save')await route.fulfill({status:503,json:{detail:'Simulated disk failure'}})
  else await route.continue()
 })
 await tray.getByRole('button',{name:'Save',exact:true}).click()
 await expect(tray.getByRole('alert')).toContainText('Simulated disk failure')
 await expect(tray).toContainText(card.name)
 await tray.getByRole('button',{name:'Reload stored draft'}).click()
 await expect(tray.getByRole('alert')).toHaveCount(0)
 await expect(tray).toContainText('IN PROGRESS')
})

